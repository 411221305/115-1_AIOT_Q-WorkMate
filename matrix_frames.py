def make_pomodoro_frame(percent: float) -> list[int]:
    """產出番茄鐘專注倒數進度點陣圖 (8x13 = 104 點).
    
    外圍是邊框，內部進度格條隨 percent (0.0~1.0) 漸漸填滿或減少。
    """
    percent = max(0.0, min(1.0, percent))
    frame = [0] * FRAME_SIZE
    
    # 頂部標題: 'F' (Focus)
    # 底部顯示水平進度條 (Row 6, 7 各 13 格，共 26 格)
    total_bars = 26
    filled = int(round(percent * total_bars))
    
    # 上半部畫一個時鐘沙漏或雙眼 (Row 1~4)
    # Row 1-2 眼睛
    for c in (3, 4, 8, 9):
        frame[1 * 13 + c] = 7
        frame[2 * 13 + c] = 7
        
    # Row 6, 7 進度條
    for i in range(filled):
        if i < 13:
            frame[6 * 13 + i] = 5
        else:
            frame[7 * 13 + (i - 13)] = 7
            
    return frame
